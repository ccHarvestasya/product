"""Reproduces the public fixed-base Ed25519 table used by the CUDA kernel."""

from pathlib import Path

PRIME = 2 ** 255 - 19
CURVE_D = -121665 * pow(121666, PRIME - 2, PRIME) % PRIME
BASE_Y = 4 * pow(5, PRIME - 2, PRIME) % PRIME
BASE_X = 15112221349535400772501151409588531511454012693041857206046113283949847762202


def add_points(left, right):
	"""Adds affine points using the twisted Edwards equation with a = -1."""

	x_left, y_left = left
	x_right, y_right = right
	product = CURVE_D * x_left * x_right * y_left * y_right % PRIME
	return (
		(x_left * y_right + y_left * x_right) * pow(1 + product, PRIME - 2, PRIME) % PRIME,
		(y_left * y_right + x_left * x_right) * pow(1 - product, PRIME - 2, PRIME) % PRIME
	)


def generate_table():
	"""Encodes multiples 1..8 of 256**i * B, for i = 0..31, as 16-bit limbs."""

	lines = [
		'// Generated by scripts/generate_ed25519_table.py; public curve points only.',
		'__constant__ unsigned short ED_BASE[32][8][3][16] = {'
	]
	base = (BASE_X, BASE_Y)
	for _ in range(32):
		lines.append('\t{')
		point = (0, 1)
		for _ in range(8):
			point = add_points(point, base)
			x_coord, y_coord = point
			lines.append('\t\t{')
			for coordinate in ((y_coord + x_coord) % PRIME, (y_coord - x_coord) % PRIME, 2 * CURVE_D * x_coord * y_coord % PRIME):
				limbs = ', '.join(str((coordinate >> (16 * index)) & 0xFFFF) for index in range(16))
				lines.append(f'\t\t\t{{{limbs}}},')
			lines.append('\t\t},')
		lines.append('\t},')
		for _ in range(8):
			base = add_points(base, base)
	lines.append('};')
	return '\n'.join(lines) + '\n'


if '__main__' == __name__:
	(Path(__file__).parents[1] / 'vanity' / 'ed25519_table.cuh').write_text(generate_table(), encoding='utf8')
